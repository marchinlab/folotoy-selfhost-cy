# -*- coding: utf-8 -*-
"""探针：测新增「资料评价」元评论正则的命中/误伤，纯内存、唔改生产。"""
import re, sys
sys.stdout.reconfigure(encoding="utf-8")

# 候选规则：整句内含「资料/資料 + (写/讲/講/寫)得/写明/讲明 + 清清楚楚/清楚」，
# 或「资料 + 清清楚楚 + 写明/讲明」强绑定。目标系「评价资料来源本身」嘅元话语。
CAND = re.compile(
    r"(?:就[系係]?\s*)?[资資]料[^。！？!?\n]{0,10}?"
    r"(?:清清楚楚|写得清楚|寫得清楚|讲得清楚|講得清楚|写得好清楚|寫得好清楚)"
    r"[^。！？!?\n]{0,10}?"
    r"(?:写明|寫明|讲明|講明|写明嘅|寫明嘅|嘅|)[。！？!?]?"
)

# 更精准第二候选：只锁「资料…清清楚楚…写明/讲明/嘅」= 评价资料来源，
# 必须同时有「资料」+「清清楚楚」+「写明/讲明/嘅/嘅」三者，避免「资料讲到嘅事实」正常引用。
CAND2 = re.compile(
    r"(?:就[系係]?\s*)?[资資]料[^。！？!?\n]{0,12}?清清楚楚[^。！？!?\n]{0,12}?"
    r"(?:写明|寫明|讲明|講明|嘅|写明嘅|寫明嘅)[，,]?[。！？!?]?"
)

POSTIVE = [  # 该命中
    "呢个年份唔好记错，就系资料清清楚楚写明嘅。",
    "就系资料清清楚楚写明嘅。",
    "资料讲得清清楚楚，唔好乱改。",
    "呢个時间点，资料讲得清清楚楚，唔好乱改。",
    "年份系资料清清楚楚写明嘅，唔好改。",
    "資料清清楚楚寫明嘅。",
]
NEGATIVE = [  # 绝不能命中
    "好似你站喺江边望对面，啲树影映在水里，远望得清清楚楚。",   # 正常描写
    "个字写得好清楚，一眼就睇明。",                            # 正常描写（无资料）
    "资料讲到嘅事实，人名、地名、年份，一律照原样讲。",        # 正常引用资料
    "批资料入面有啲系全国时政，要照实讲。",                    # 正常引用
    "过马路唔好乱跑，唔好乱爬细路。",                          # 安全教育
    "但唔好以为唐朝就唔好，中后期都有贡献。",                  # 正常论述
    "唐顺宗做皇太子，长达二十六年，因为佢爹德宗喺位時间长。",   # 知识
    "呢部分我搵唔到确切资料，唔敢乱作。",                      # 诚实坦白
]

for name, pat in [("CAND", CAND), ("CAND2", CAND2)]:
    print("\n===== %s =====" % name)
    print("-- 正向（期望命中）--")
    for s in POSTIVE:
        m = pat.search(s)
        print("  [%s] %s  -> %r" % ("HIT" if m else "MISS", s, m.group(0) if m else ""))
    print("-- 反向（期望 MISS）--")
    for s in NEGATIVE:
        m = pat.search(s)
        print("  [%s] %s  -> %r" % ("BAD-HIT!" if m else "ok", s, m.group(0) if m else ""))

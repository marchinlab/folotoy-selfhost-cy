# -*- coding: utf-8 -*-
"""v1.30 单元回归：9 词正音落地 + 一对多/双关字零误伤 + 幂等 + 全历史零回归。
只测 tts_pron.fix 层（正音落点），唔依赖网络。"""
import sys
import tts_pron

ok_n = fail_n = 0


def ok(name, cond, extra=""):
    global ok_n, fail_n
    if cond:
        ok_n += 1
        print("  PASS %-40s %s" % (name, extra))
    else:
        fail_n += 1
        print("  FAIL %-40s %s" % (name, extra))


def F(s):
    return tts_pron.fix(s)


print("=== 1) v1.30 单字正音落地（9 词涉及）===")
for a, b in [("净力", "淨力"), ("干净", "干淨"), ("陈桥", "陳桥"), ("姓陈", "姓陳"),
             ("一齐", "一齊"), ("整齐", "整齊"), ("组队", "組隊"), ("小组", "小組"),
             ("队伍", "隊伍"), ("火药", "火藥"), ("吃药", "吃藥"),
             ("文风", "聞風"), ("质量", "質量"), ("本质", "本質")]:
    ok("fix %s -> %s" % (a, b), F(a) == b, "| got %s" % F(a))

print("=== 2) 词级一对多 / 换字 ===")
ok("发达 -> 發達", F("发达") == "發達", "| %s" % F("发达"))
ok("文风 -> 聞風（唔系文風）", F("文风") == "聞風", "| %s" % F("文风"))
ok("文风鼎盛 -> 聞風鼎盛", F("文风鼎盛") == "聞風鼎盛", "| %s" % F("文风鼎盛"))
# 「文」单字唔全局换（护语文/文化/作文）
for w in ["语文", "文化", "作文", "课文", "文章", "文字"]:
    ok("护 %s 唔变聞" % w, "聞" not in F(w), "| %s" % F(w))

print("=== 3) 一对多「发」零误伤（发→發 只放行发达）===")
for w in ["头发", "发现", "发生", "发言", "发型", "理发", "发抖"]:
    ok("护 %s 原样" % w, F(w) == w, "| %s" % F(w))

print("=== 4) 「过程」保持简体（声学验证本就啱，转繁反而错）===")
ok("过程 原样", F("过程") == "过程", "| %s" % F("过程"))
ok("過情 原样", F("過情") == "過情", "| %s" % F("過情"))

print("=== 5) 全历史零回归（v1.24~v1.28）===")
# 注意：fix 只替换【已验证易误读字】，唔系全繁简表。故只校验目标字落地，
#      非目标字（机/词/计/简/名...）保持原样系【正确行为】，唔好写死全繁期望值。
for a, b in [("机会", "机會"), ("会计", "會计"), ("合适", "合適"), ("地区", "地區"),
             ("单词", "單词"), ("单位", "單位"), ("简单", "简單"), ("名单", "名單"),
             ("听日", "汀日"), ("聽日", "汀日"), ("听朝", "汀朝"), ("听晚", "汀晚")]:
    ok("历史 %s -> %s" % (a, b), F(a) == b, "| %s" % F(a))
# 「听」只在时间词换汀；好听/听见/听歌 嘅「听」本来就念对，必须原样（v1.24 设计）
for w in ["好听", "听见", "听歌", "听力"]:
    ok("历史护 %s 原样" % w, F(w) == w, "| %s" % F(w))

print("=== 6) 幂等 + 非 str 原样 ===")
mixed = "听日背单词，机会合适，净力质量陈桥组队，发达火药文风一齐过程。"
once = F(mixed)
ok("幂等 fix(fix(x))==fix(x)", F(once) == once, "| %s" % once)
ok("fix(123) 原样", F(123) == 123)
ok("fix(None) 原样", F(None) is None)

print("\n=== 结果: PASS %d / FAIL %d ===" % (ok_n, fail_n))
sys.exit(1 if fail_n else 0)

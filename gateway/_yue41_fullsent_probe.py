# -*- coding: utf-8 -*-
"""探针：整句删除版「资料评价」元评论规则，验证删净不残留 + 零误伤。"""
import re, sys
sys.stdout.reconfigure(encoding="utf-8")

# 整句级：整句含「资料」+「(讲/写)得清清楚楚 / 清清楚楚写明 / 写得清楚」等评价，
# 吞掉整句（含可选前导「呢个時间点，」「就系」「呢个年份唔好记错，」+ 句末标点）。
# 关键：以句末标点为界，绝不跨句；[资資]料 与 清楚 必须同句。
META_FULL = re.compile(
    r"(?:^|(?<=[。！？!?；;\n]))\s*"          # 句首边界
    r"[^。！？!?；;\n]{0,24}?"                # 可选前缀（如「呢个時间点，」「呢个年份唔好记错，」「就系」）
    r"[资資]料[^。！？!?；;\n]{0,12}?"
    r"(?:清清楚楚|写得清楚|寫得清楚|讲得清楚|講得清楚|写得好清楚|寫得好清楚)"
    r"[^。！？!?；;\n]{0,16}?"                # 后缀（「，唔好乱改」「写明嘅」「」）
    r"[。！？!?]"                             # 句末标点（必须有，确保删整句）
)

POSTIVE = [
    ("呢个時间点，资料讲得清清楚楚，唔好乱改。", True),
    ("呢个年份唔好记错，就系资料清清楚楚写明嘅。", True),
    ("就系资料清清楚楚写明嘅。", True),
    ("资料写得清清楚楚，唔好改。", True),
    ("年份系资料清清楚楚写明嘅，唔好改。", True),
    ("資料清清楚楚寫明嘅。", True),
    ("唐朝开国系李渊起兵。呢个時间点，资料讲得清清楚楚，唔好乱改。佢618年称帝。", True),  # 嵌段
]
NEGATIVE = [
    ("好似你站喺江边望对面，啲树影映在水里，远望得清清楚楚。", False),
    ("个字写得好清楚，一眼就睇明。", False),
    ("资料讲到嘅事实，人名、地名、年份，一律照原样讲。", False),
    ("批资料入面有啲系全国时政，要照实讲。", False),
    ("过马路唔好乱跑，唔好乱爬细路。", False),
    ("但唔好以为唐朝就唔好，中后期都有贡献。", False),
    ("唐顺宗做皇太子，长达二十六年，因为佢爹德宗喺位時间长。", False),
    ("呢部分我搵唔到确切资料，唔敢乱作。", False),
    ("唐太宗唔单止打仗厉害，仲识得用人，资料讲到嘅都照讲。", False),
]

print("=== 正向（期望删净，残留不含资料/清楚）===")
for s, _ in POSTIVE:
    m = META_FULL.search(s)
    out = META_FULL.sub("", s).strip() if m else s
    ok = m and ("清清楚楚" not in out) and ("資料" not in out and "资料" not in out or "资料讲" in out)
    print("  [%s] IN=%s" % ("HIT " if m else "MISS", s))
    print("        OUT=|%s|" % out)
print("=== 反向（期望 MISS，原样保留）===")
for s, _ in NEGATIVE:
    m = META_FULL.search(s)
    print("  [%s] %s" % ("BAD-HIT!" if m else "ok     ", s))
